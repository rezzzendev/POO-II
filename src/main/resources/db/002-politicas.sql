ALTER TABLE eventos ADD COLUMN IF NOT EXISTS local VARCHAR(255) DEFAULT 'A definir' NOT NULL;
ALTER TABLE eventos ADD COLUMN IF NOT EXISTS fuso VARCHAR(100) DEFAULT 'America/Sao_Paulo' NOT NULL;
CREATE TABLE IF NOT EXISTS regras_inscricao (
 evento_id BIGINT PRIMARY KEY REFERENCES eventos(id) ON DELETE CASCADE,
 escolher_atividades BOOLEAN NOT NULL, controlar_vagas BOOLEAN NOT NULL,
 prazo_cancelamento TIMESTAMP NOT NULL
);
CREATE TABLE IF NOT EXISTS politicas_frequencia (
 atividade_id BIGINT PRIMARY KEY REFERENCES atividades(id) ON DELETE CASCADE,
 tipo VARCHAR(30) NOT NULL
);
CREATE TABLE IF NOT EXISTS codigos_frequencia (
 token VARCHAR(100) PRIMARY KEY, atividade_id BIGINT NOT NULL REFERENCES atividades(id) ON DELETE CASCADE,
 tipo VARCHAR(30) NOT NULL, validade TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE TABLE IF NOT EXISTS registros_frequencia (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 atividade_id BIGINT NOT NULL REFERENCES atividades(id) ON DELETE CASCADE,
 usuario_id BIGINT NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
 tipo VARCHAR(30) NOT NULL, origem VARCHAR(20) NOT NULL,
 responsavel_id BIGINT NOT NULL REFERENCES usuarios(id), instante TIMESTAMP WITH TIME ZONE NOT NULL,
 justificativa VARCHAR(1000) NOT NULL
);
CREATE TABLE IF NOT EXISTS questionarios (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 atividade_id BIGINT NOT NULL REFERENCES atividades(id) ON DELETE CASCADE,
 titulo VARCHAR(255) NOT NULL, politica_identificacao VARCHAR(1000) NOT NULL
);
CREATE TABLE IF NOT EXISTS perguntas (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 questionario_id BIGINT NOT NULL REFERENCES questionarios(id) ON DELETE CASCADE,
 enunciado VARCHAR(1000) NOT NULL, tipo VARCHAR(30) NOT NULL,
 minimo INT NOT NULL, maximo INT NOT NULL
);
CREATE TABLE IF NOT EXISTS opcoes_pergunta (
 pergunta_id BIGINT NOT NULL REFERENCES perguntas(id) ON DELETE CASCADE,
 ordem INT NOT NULL, texto VARCHAR(500) NOT NULL, PRIMARY KEY(pergunta_id, ordem)
);
CREATE TABLE IF NOT EXISTS avaliacoes (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 questionario_id BIGINT NOT NULL REFERENCES questionarios(id) ON DELETE CASCADE,
 usuario_id BIGINT NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
 instante TIMESTAMP WITH TIME ZONE NOT NULL, UNIQUE(questionario_id, usuario_id)
);
CREATE TABLE IF NOT EXISTS respostas (
 avaliacao_id BIGINT NOT NULL REFERENCES avaliacoes(id) ON DELETE CASCADE,
 pergunta_id BIGINT NOT NULL REFERENCES perguntas(id), valor VARCHAR(4000) NOT NULL,
 PRIMARY KEY(avaliacao_id, pergunta_id)
);
CREATE INDEX IF NOT EXISTS idx_frequencia_participante ON registros_frequencia(atividade_id,usuario_id);
CREATE INDEX IF NOT EXISTS idx_inscricao_evento ON inscricoes(evento_id,status);
